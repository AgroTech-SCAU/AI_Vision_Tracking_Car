"""
============================================================

============================================================

用法:
    python train.py

数据:
    datasets/images/train/   — 训练图片
    datasets/images/val/     — 验证图片
    datasets/labels/train/   — YOLO 格式标注
    datasets/labels/val/     — YOLO 格式标注
    datasets/data.yaml           — 数据集配置
"""

from ultralytics import YOLO
import os

# 脚本所在目录，所有路径都基于此目录
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def main():
    # ========================================
    # 基础配置
    # ========================================
    from datetime import datetime
    DATA_YAML = os.path.join(SCRIPT_DIR, "datasets",  "data.yaml")
    MODEL_NAME = os.path.join(SCRIPT_DIR, "yolo11n.pt")
    PROJECT = os.path.join(SCRIPT_DIR, "runs", "person_detection")

    # 每次训练用时间戳自动命名，不会覆盖之前的结果
    EXPERIMENT = datetime.now().strftime("%m%d_%H%M")

    # ========================================
    # 训练超参数（每个参数的含义和调参建议见下方注释）
    # ========================================
    EPOCHS = 50                            # 训练总轮数
    IMGSZ = 640                             # 输入图像尺寸
    BATCH = 8                               # 每批图片数量
    DEVICE = 0                              # GPU 编号 (0/1/2...)，无 GPU 改为 "cpu"

    # ========================================
    # 检查环境
    # ========================================
    if not os.path.exists(DATA_YAML):
        raise FileNotFoundError(f"数据集配置文件不存在: {DATA_YAML}")

    print(f"数据配置: {DATA_YAML}")
    print(f"预训练模型: {MODEL_NAME}")
    print(f"训练轮数: {EPOCHS}, Batch: {BATCH}, 图片尺寸: {IMGSZ}")

    # ========================================
    # 加载预训练模型
    # ========================================
    model = YOLO(MODEL_NAME)

    # ========================================
    # 开始训练
    # ========================================
    results = model.train(
        # ============================================================
        # 一、数据配置
        # ============================================================
        data=DATA_YAML,             # 数据集 yaml 路径，内含 train/val 路径和类别名

        # ============================================================
        # 二、训练核心参数
        # ============================================================

        epochs=EPOCHS,

        imgsz=IMGSZ,
        # 作用: 训练时把图片缩放到这个尺寸 (正方形)
        # 当前: 640。YOLO 标准尺寸，兼顾速度和精度
        # 调整: 你的视频是 1920x1080，大框小框都有。
        #        想让小目标更准 → 960（更慢但更准，显存占用翻倍）
        #        显存不够或追求速度 → 480（更快但可能漏小目标）

        batch=BATCH,
        # 作用: 每次迭代同时处理的图片数
        # 当前: 4。RTX 5060 8GB 显存的安全值
        # 调整: 显存够就加大。8 → 16 每档翻倍测试，显存满了就减
        #        batch 越大梯度越稳定，但太大可能收敛到局部最优

        device=DEVICE,
        # 作用: 指定计算设备
        # 调整: 单 GPU 用 0；双卡用 [0,1]；CPU 用 "cpu"（极慢，不推荐）

        workers=0,
        # 在主进程加载数据，尝试绕过 Windows 下多进程与权重序列化相关的 closed file 报错。
        # 数据加载可能变慢；此配置仍需重新训练验证。

        amp=False,
        # 作用: 自动混合精度训练。开启后显存占用减半、速度加快
        # 当前: False。因为国内网络无法从 GitHub 下载 AMP 检查模型，
        #        如果你能翻墙或离线下载了 yolo26n.pt，改为 True 可提速
        # 调整: 网络能访问 GitHub → True；有 NaN loss 问题 → False

        # ============================================================
        # 三、优化器与学习率
        # ============================================================

        optimizer="AdamW",
        # 作用: AdamW 带权重衰减，对小数据集和微调场景比 SGD 更稳定
        # 可选: "SGD" 收敛慢但泛化好；"Adam" 收敛快但可能过拟合；"AdamW" 折中
        # 调整: 数据量大(>1万张)可换 SGD 追求更好泛化；当前场景保持 AdamW

        lr0=1e-3,
        # 作用: 初始学习率。决定每一步参数更新的幅度
        # 当前: 0.001。适中值，配合 AdamW 使用
        # 调整: loss 震荡(忽高忽低) → 减小到 5e-4
        #        loss 下降太慢 → 增大到 5e-3
        #        用的 SGD 优化器 → 建议 1e-2（SGD 需要更大 lr）

        lrf=1e-4,
        # 作用: 最终学习率 = lr0 × lrf。训练结束时 lr 降到这个值
        # 当前: 1e-4，等于 0.001 × 0.1 = 0.0001
        # 调整: 想更充分收敛 → 1e-5（更小终点）；怕过拟合 → 5e-4

        weight_decay=5e-4,
        # 作用: L2 正则化系数，防止权重过大导致过拟合
        # 当前: 0.0005。标准值
        # 调整: 验证集远差于训练集(过拟合) → 增大到 1e-3
        #        训练集 loss 下不去(欠拟合) → 减小到 1e-4

        warmup_epochs=3,
        # 作用: 前 N 轮学习率从 0 逐渐升到 lr0，避免训练初期震荡
        # 当前: 3 轮。小数量训练的标准值
        # 调整: 数据量大或 batch 大 → 5 轮；数据量少 → 2 轮

        # ============================================================
        # 四、数据增广（模拟不同拍摄条件，防止模型死记硬背）
        # ============================================================

        hsv_h=0.015,
        # 作用: 色调随机偏移。模拟不同白平衡和光照色温
        # 范围: 0-1。0.015 ≈ 5.4° 偏移
        # 调整: 不同场地灯光差很多 → 0.03；场景固定 → 0.01

        hsv_s=0.7,
        # 作用: 饱和度随机缩放。模拟不同相机饱和度设置
        # 调整: 0-1。越大颜色变化越剧烈。0.5-0.7 都正常

        hsv_v=0.4,
        # 作用: 亮度随机缩放。模拟不同曝光/光线强度
        # 调整: 0-1。户外光线变化大 → 0.5-0.6；室内固定灯光 → 0.2-0.3

        degrees=10.0,
        # 作用: 随机旋转角度。模拟摄像机不是水平摆放
        # 当前: ±10°
        # 调整: 固定摄像机 → 0-5；手持/移动摄像机 → 15-30

        translate=0.1,
        # 作用: 随机平移。模拟目标不在画面中心
        # 调整: 0-0.3。目标总是在中间 → 大一点；目标分布均匀 → 小一点

        scale=0.5,
        # 作用: 随机缩放。模拟同一目标在不同距离的大小变化
        # 当前: ±50%。网球运动员在画面中大小变化大，设大一点合理
        # 调整: 目标大小固定 → 0.2-0.3；远近变化大 → 0.5-0.7

        shear=3.0,
        # 作用: 随机剪切变形。模拟不同拍摄角度
        # 调整: 0-5。正面拍摄 → 小；侧面/斜拍多 → 大

        perspective=0.0005,
        # 作用: 随机透视变换强度
        # 调整: 0-0.001。过大会产生不真实变形

        flipud=0.0,
        # 作用: 上下翻转概率。50% 的图上下颠倒
        # ⚠ 警告: 网球场景中人是站着的，上下翻转会产生倒立的人！
        #          建议改为 0.0，除非你的视频里确实有倒立的人
        # 调整: 网球运动员 → 0.0；无人机俯拍 → 0.5

        fliplr=0.5,
        # 作用: 左右翻转概率。模拟左手/右手球员
        # 当前: 50%。合理，网球选手左右手都有
        # 调整: 只检测一个方向的场景 → 0.0

        mosaic=0.5,
        # 作用: 将 4 张图拼成 1 张训练。增加小目标和背景多样性
        # 当前: 1.0 = 100% 使用。前 close_mosaic 轮使用
        # 调整: 小目标多 → 保持 1.0；都是大目标 → 0.3-0.5

        mixup=0.1,
        # 作用: 两张图按比例混合。让模型学得更鲁棒，防止过拟合
        # 当前: 10% 概率触发
        # 调整: 数据量少(<1000) → 0.2-0.3；数据量多 → 0.05-0.1

        copy_paste=0.1,
        # 作用: 把一张图的实例粘贴到另一张图。增加实例多样性
        # 当前: 10% 概率触发
        # 调整: 每张图实例少(1-2人) → 0.2-0.3 增加多样性；
        #        每张图人多 → 0.05-0.1

        # ============================================================
        # 五、保存与输出
        # ============================================================

        save=True,
        # 作用: 是否保存模型文件

        save_period=20,
        # 作用: 每隔 N 轮保存一次模型快照
        # 当前: 20。可用来回退到某轮的模型
        # 调整: 想精确定位最佳轮次 → 5-10；节省磁盘 → 50

        pretrained=True,
        # 作用: 使用预训练权重初始化。必开，不开从头训要几十万张图

        project=PROJECT,
        # 作用: 所有训练输出的大目录
        # 输出位置: runs/person_detection/

        name=EXPERIMENT,
        # 作用: 本次训练的子目录名（时间戳自动生成）
        # 输出位置: runs/person_detection/0723_1651/

        exist_ok=True,
        # 作用: 允许覆盖同名目录。时间戳命名下一般不会重名，安全

        # ============================================================
        # 六、验证
        # ============================================================

        val=True,
        # 作用: 每轮训练后在验证集上评估 mAP。必开

        plots=True,
        # 作用: 生成训练曲线图（results.png）。Loss 曲线、mAP 曲线等
        # 输出位置: runs/person_detection/xxx/results.png
    )

    # ========================================
    # 训练完成
    # ========================================
    best_pt = os.path.join(PROJECT, EXPERIMENT, "weights", "best.pt")
    print(f"\n训练完成！最佳模型: {best_pt}")
    print(f"追踪推理: python track.py --model {best_pt} --source <视频>")

    return results


if __name__ == "__main__":
    main()
